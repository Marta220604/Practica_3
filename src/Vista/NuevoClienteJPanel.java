    //lee los campos, los valida con la clase control de errores y  si todo es correcto añade el cliente
    //Si algo falla escribe el motivo en el JLabel rojo y no añade nada
    public void añadirCliente() {
        jLabelError.setText(""); // borra el error del intento anterior
        try {
            // leemos las variables y las convertimos (si el texto no es un numero/fecha valida salta al catch)
            String nombre = TextFieldNombre.getText().trim();
            int numero = Integer.parseInt(TextFieldNumero.getText().trim());
            int edad = Integer.parseInt(TextFieldEdad.getText().trim());
            float puntos = Float.parseFloat(TextFieldPuntos.getText().trim());
            LocalDate fecha = LocalDate.parse(TextFieldFechaN.getText().trim()); 

            // Comprobamos que los datos introducidos son correctos utilizando la clase de control de errores
            if (nombre.isEmpty()) {
                jLabelError.setText("El nombre no puede estar vacío");
            } else if (!ControlErrores.comprobarPuntos(puntos)) {
                jLabelError.setText("Los puntos deben estar entre 0 y 1000");
            } else if (!ControlErrores.comprobarFecha(fecha)) {
                jLabelError.setText("La fecha debe estar entre 1900 y 2015");
            } else {
                // si todo esta bien añadimos un nuevo cliente y volvemos a poner los campos en blanco
                gestion.añadirCliente(new Cliente(numero, nombre, edad, puntos, fecha));
                TextFieldNumero.setText("");
                TextFieldNombre.setText("");
                TextFieldEdad.setText("");
                TextFieldFechaN.setText("");
                TextFieldPuntos.setText("");
            }
        } catch (NumberFormatException e) {
            jLabelError.setText("Número, edad y puntos deben ser numéricos");
        } catch (DateTimeParseException e) {
            jLabelError.setText("Fecha incorrecta, usa el formato aaaa-mm-dd");
        }
    }

